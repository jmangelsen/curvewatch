import assert from 'node:assert/strict';
import {streamReplay} from '../src/edgelab/replayStream.js';
import {exitLabelStore} from '../src/edgelab/exitLabels.js';
const rows=[{entry_ts:1,n:5},{entry_ts:2,n:2},{entry_ts:3,n:8}];
const rules=[{P:{gain:.1}},{P:{gain:-.2}}];
const calls=[];
const actual=streamReplay(rows,rules,r=>{calls.push(`load${r.entry_ts}`);return Array(r.n).fill(1);},({r},p)=>{calls.push(`sim${r.entry_ts}`);return r.entry_ts*p.gain;});
assert.equal(actual.withTape,2);
assert.deepEqual(actual.values,[[{ts:1,net:10},{ts:3,net:30.000000000000004}],[{ts:1,net:-20},{ts:3,net:-60.00000000000001}]]);
console.log('ok streaming replay retains the same per-rule returns');
assert.deepEqual(calls,['load1','sim1','sim1','load2','load3','sim3','sim3']);
console.log('ok each tape is simulated before loading the next one');
assert.deepEqual(streamReplay(rows,rules,r=>Array(5),()=>null),{withTape:3,values:[[],[]]});
console.log('ok missing simulated fills are excluded rather than zero returns');
const labels=exitLabelStore([60,120,600]);
labels.put('a',60,100);labels.put('a',600,200);labels.put('b',120,0);
assert.equal(labels.get('a',60),100);assert.equal(labels.get('a',600),200);
assert.equal(labels.get('a',120),undefined);assert.equal(labels.get('missing',60),undefined);
assert.equal(labels.get('b',120),0);
labels.put('a',60,101);assert.equal(labels.get('a',60),101);
console.log('ok dense exit labels preserve missing, zero, overwrite and horizon semantics');
console.log('4 bounded replay tests passed');
